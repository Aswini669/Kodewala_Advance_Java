package com.streamapi.studentgradequestions;

public class Students {

	String name;
	String grade;
	
	public Students(String name, String grade) {
		this.name = name;
		this.grade = grade;
	}
	
	public String getName() {
		return name;
	}
	
	public String getGrade() {
		return grade;
	}
	
	public String toString() {
		return name;
	}
	
	
}
